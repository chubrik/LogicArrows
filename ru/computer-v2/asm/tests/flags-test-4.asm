                ldi d, terminal     ; В регистре D постоянно лежит адрес для вывода в терминал
                ldi c, "A" - 1      ; Счётчик проб
                ldi b, "4"          ; Маркер номера дискеты
                st b, d

; Случай 1 (канарейка): add 255+1, ожидаем C=1, O=0
                inc c
                ldi a, 255
                ldi b, 1
                add a, b
                jc t1o
                st c, d             ; "A" = нет переноса после add 255+1
t1o:            inc c
                jno t2
                st c, d             ; "B" = ложное переполнение после add 255+1

; Случай 2: cmp 5, 3 - больше в обеих трактовках, ожидаем Z=0, S=0, C=0
t2:             inc c
                ldi a, 5
                ldi b, 3
                cmp a, b
                jnz t2s
                st c, d             ; "C" = ложное равенство после cmp 5, 3
t2s:            inc c
                jns t2c
                st c, d             ; "D" = ложное знаковое меньше после cmp 5, 3
t2c:            inc c
                jnc t3
                st c, d             ; "E" = ложное беззнаковое меньше после cmp 5, 3

; Случай 3: cmp 3, 5 - меньше в обеих трактовках, ожидаем S=1, C=1, O=0
t3:             inc c
                ldi a, 3
                ldi b, 5
                cmp a, b
                js t3c
                st c, d             ; "F" = нет знакового меньше после cmp 3, 5
t3c:            inc c
                jc t3o
                st c, d             ; "G" = нет беззнакового меньше после cmp 3, 5
t3o:            inc c
                jno t4
                st c, d             ; "H" = ложное переполнение после cmp 3, 5
                jmp t4

void        db  0, 0

; Порты (грузятся вместе с дискетой; значение in_out подключает терминал уже при загрузке)
bcd         db  0, 0
terminal    db  0, 0
in_out      db  0b00000001
bank        db  0

; Случай 4: cmp 5, 5 - равенство, ожидаем Z=1, S=0, C=0
t4:             inc c
                ldi a, 5
                ldi b, 5
                cmp a, b
                jz t4s
                st c, d             ; "I" = нет равенства после cmp 5, 5
t4s:            inc c
                jns t4c
                st c, d             ; "J" = ложное знаковое меньше после cmp 5, 5
t4c:            inc c
                jnc t5
                st c, d             ; "K" = ложное беззнаковое меньше после cmp 5, 5

; Случай 5: cmp 255, 1 - трактовки расходятся: -1 < 1 знаково, 255 > 1 беззнаково.
; Ожидаем S=1, C=0, O=0
t5:             inc c
                ldi a, 255
                ldi b, 1
                cmp a, b
                js t5c
                st c, d             ; "L" = нет знакового меньше после cmp 255, 1
t5c:            inc c
                jnc t5o
                st c, d             ; "M" = ложное беззнаковое меньше после cmp 255, 1
t5o:            inc c
                jno t6
                st c, d             ; "N" = ложное переполнение после cmp 255, 1

; Случай 6: cmp 1, 255 - зеркало случая 5: 1 > -1 знаково, 1 < 255 беззнаково. Ожидаем S=0, C=1, O=0
t6:             inc c
                ldi a, 1
                ldi b, 255
                cmp a, b
                jns t6c
                st c, d             ; "O" = ложное знаковое меньше после cmp 1, 255
t6c:            inc c
                jc t6o
                st c, d             ; "P" = нет беззнакового меньше после cmp 1, 255
t6o:            inc c
                jno t7
                st c, d             ; "Q" = ложное переполнение после cmp 1, 255

; Случай 7: cmp 200, 100 - разность -56-100 переполняется, и её сырой бит 7 врёт про плюс;
; истинный знаковый ответ: -56 < 100. Ожидаем S=1, C=0, O=1
t7:             inc c
                ldi a, 200
                ldi b, 100
                cmp a, b
                js t7c
                st c, d             ; "R" = нет знакового меньше после cmp 200, 100
t7c:            inc c
                jnc t7o
                st c, d             ; "S" = ложное беззнаковое меньше после cmp 200, 100
t7o:            inc c
                jo t8
                st c, d             ; "T" = нет переполнения после cmp 200, 100

; Случай 8: cmp 100, 200 - зеркало случая 7, сырой бит 7 врёт про минус. Ожидаем S=0, C=1, O=1
t8:             inc c
                ldi a, 100
                ldi b, 200
                cmp a, b
                jns t8c
                st c, d             ; "U" = ложное знаковое меньше после cmp 100, 200
t8c:            inc c
                jc t8o
                st c, d             ; "V" = нет беззнакового меньше после cmp 100, 200
t8o:            inc c
                jo t9
                st c, d             ; "W" = нет переполнения после cmp 100, 200

; Случай 9: cmp 128, 127 - экстремум: -128 против 127, разность -255. Ожидаем S=1, C=0, O=1
t9:             inc c
                ldi a, 128
                ldi b, 127
                cmp a, b
                js t9c
                st c, d             ; "X" = нет знакового меньше после cmp 128, 127
t9c:            inc c
                jnc t9o
                st c, d             ; "Y" = ложное беззнаковое меньше после cmp 128, 127
t9o:            inc c
                jo t10
                st c, d             ; "Z" = нет переполнения после cmp 128, 127

; Случай 10: cmp 127, 128 - зеркало случая 9: 127 против -128, разность +255. Ожидаем S=0, C=1, O=1
t10:            ldi b, 7            ; Шаг "+7": перепрыгиваем счётчиком проб коды между "Z" и "a"
                add c, b
                ldi a, 127
                ldi b, 128
                cmp a, b
                jns t10c
                st c, d             ; "a" = ложное знаковое меньше после cmp 127, 128
t10c:           inc c
                jc t10o
                st c, d             ; "b" = нет беззнакового меньше после cmp 127, 128
t10o:           inc c
                jo t11
                st c, d             ; "c" = нет переполнения после cmp 127, 128

; Случай 11: cmp 128, 128 - равенство в знаковом минимуме, ожидаем Z=1, S=0
t11:            inc c
                ldi a, 128
                ldi b, 128
                cmp a, b
                jz t11s
                st c, d             ; "d" = нет равенства после cmp 128, 128
t11s:           inc c
                jns t12
                st c, d             ; "e" = ложное знаковое меньше после cmp 128, 128

; Случай 12: cmp b, a - другой опкод, самая острая пара наоборот: 100 против -56.
; Ожидаем S=0, C=1, O=1
t12:            inc c
                ldi a, 200
                ldi b, 100
                cmp b, a
                jns t12c
                st c, d             ; "f" = ложное знаковое меньше после cmp b, a (100 против 200)
t12c:           inc c
                jc t12o
                st c, d             ; "g" = нет беззнакового меньше после cmp b, a (100 против 200)
t12o:           inc c
                jo t13
                st c, d             ; "h" = нет переполнения после cmp b, a (100 против 200)

; Случай 13: cmp a, d - пара с регистром D: в обоих лежит адрес терминала. Ожидаем Z=1, C=0
t13:            inc c
                ldi a, terminal
                cmp a, d
                jz t13c
                st c, d             ; "i" = нет равенства после cmp a, d (равные значения)
t13c:           inc c
                jnc tchk
                st c, d             ; "j" = ложное беззнаковое меньше после cmp a, d (равные
                                    ;   значения)

; Проверка счётчика: после 36 проб счётчик должен быть ровно на букве "j"
tchk:           ldi b, "j"
                xor b, c
                jz tdot
                ldi c, "#"          ; "#" = поток управления пошёл не по плану, часть проб
                                    ;   не выполнилась
                st c, d
tdot:           ldi c, "."          ; Маркер конца: программа дошла до конца
                st c, d

                hlt
