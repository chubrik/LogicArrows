                ldi d, terminal     ; В регистре D постоянно лежит адрес для вывода в терминал
                ldi c, 0x40         ; Счётчик проб: код перед буквой "A"
                ldi b, 0x32         ; Маркер номера диска: "2"
                st b, d

; Случай 1 (канарейка): add 255+1, ожидаем C=1, O=0
                inc c
                ldi a, 255
                ldi b, 1
                add a, b
                jc t1o
                st c, d             ; "A" = нет переноса после add 255+1
t1o:            inc c
                jno t2
                st c, d             ; "B" = ложное переполнение после add 255+1

; Случай 2: inc обязан сохранить C=1, O=0 (сырой перенос inc 127 равен 0, переполнение 1 -
; противоположные значения)
t2:             inc c
                ldi a, 255
                ldi b, 1
                add a, b            ; Готовим C=1, O=0
                ldi a, 127
                inc a
                jc t2o
                st c, d             ; "C" = inc 127 разрушил C=1
t2o:            inc c
                jno t3
                st c, d             ; "D" = inc 127 защёлкнул своё сырое переполнение в O

; Случай 3: inc обязан сохранить C=0, O=1 (сырой перенос inc 255 равен 1, переполнение 0 -
; противоположные значения)
t3:             inc c
                ldi a, 127
                ldi b, 1
                add a, b            ; Готовим C=0, O=1
                ldi a, 255
                inc a
                jnc t3o
                st c, d             ; "E" = inc 255 защёлкнул свой сырой перенос в C
t3o:            inc c
                jo t4
                st c, d             ; "F" = inc 255 разрушил O=1
                jmp t4

void        db  0, 0, 0, 0, 0, 0, 0, 0

; Порты
keyboard    db  0                   ; Порт клавиатуры
output      db  0x40                ; Порт выбора вывода: терминал подключается уже при загрузке
terminal    db  0                   ; Байт, отправленный сюда, печатается в терминал

; Случай 4: dec обязан сохранить C=1, O=1 (сырые перенос и переполнение dec 0 равны 0)
t4:             inc c
                ldi a, 128
                ldi b, 128
                add a, b            ; Готовим C=1, O=1
                mov a, 0
                dec a
                jc t4o
                st c, d             ; "G" = dec 0 разрушил C=1
t4o:            inc c
                jo t5
                st c, d             ; "H" = dec 0 разрушил O=1

; Случай 5: dec обязан сохранить C=0, O=1 (сырой перенос dec 5 равен 1, переполнение 0)
t5:             inc c
                ldi a, 127
                ldi b, 1
                add a, b            ; Готовим C=0, O=1
                ldi a, 5
                dec a
                jnc t5o
                st c, d             ; "I" = dec 5 защёлкнул свой сырой перенос в C
t5o:            inc c
                jo t6
                st c, d             ; "J" = dec 5 разрушил O=1

; Случай 6: not обязан сохранить C=1, O=1. Операнд - ноль, оставшийся в A после подготовительного
; add.
t6:             inc c
                ldi a, 128
                ldi b, 128
                add a, b            ; Готовим C=1, O=1; A = 0
                not a
                jc t6o
                st c, d             ; "K" = not разрушил C=1
t6o:            inc c
                jo t7
                st c, d             ; "L" = not разрушил O=1

; Случай 7: mov обязан сохранить C=1, O=1 (вообще не операция АЛУ)
t7:             inc c
                ldi a, 128
                ldi b, 128
                add a, b            ; Готовим C=1, O=1
                mov a, b
                jc t7o
                st c, d             ; "M" = mov разрушил C=1
t7o:            inc c
                jo t8
                st c, d             ; "N" = mov разрушил O=1

; Случай 8: shr 5 обязан установить C=1 из выдвинутого бита и сохранить O=1
t8:             inc c
                ldi a, 127
                ldi b, 1
                add a, b            ; Готовим C=0, O=1
                ldi a, 5
                shr a
                jc t8o
                st c, d             ; "O" = shr 5 не установил C из выдвинутого бита
t8o:            inc c
                jo t9
                st c, d             ; "P" = shr разрушил O=1

; Проверки NEG: ведёт себя как sub с нулём слева - C при ненулевом операнде, O только на 128

; Случай 9: neg 5 с подготовленными C=0, O=0, ожидаем C=1, O=0
t9:             inc c
                ldi a, 1
                ldi b, 1
                add a, b            ; Готовим C=0, O=0
                ldi a, 5
                neg a
                jc t9o
                st c, d             ; "Q" = нет переноса после neg 5
t9o:            inc c
                jno t10
                st c, d             ; "R" = ложное переполнение после neg 5

; Случай 10: neg 5 с подготовленным C=1, ожидаем C=1, O=0
t10:            inc c
                ldi a, 255
                ldi b, 1
                add a, b            ; Готовим C=1, O=0
                ldi a, 5
                neg a
                jc t10o
                st c, d             ; "S" = нет переноса после neg 5 при подготовленном C=1
t10o:           inc c
                jno t11
                st c, d             ; "T" = ложное переполнение после neg 5 при подготовленном C=1

; Случай 11: neg 0 с подготовленным C=1, ожидаем C=0, O=0
t11:            inc c
                ldi a, 255
                ldi b, 1
                add a, b            ; Готовим C=1, O=0
                mov a, 0
                neg a
                jnc t11o
                st c, d             ; "U" = neg 0 не сбросил C=1
t11o:           inc c
                jno t12
                st c, d             ; "V" = ложное переполнение после neg 0

; Случай 12: neg 128 с подготовленными C=0, O=0, ожидаем C=1, O=1 (у -128 нет пары)
t12:            inc c
                ldi a, 1
                ldi b, 1
                add a, b            ; Готовим C=0, O=0
                ldi a, 128
                neg a
                jc t12o
                st c, d             ; "W" = нет переноса после neg 128
t12o:           inc c
                jo t13
                st c, d             ; "X" = нет переполнения после neg 128 (у -128 нет пары)

; Случай 13: прямой sbb: 5-3-1 с подготовленным C=1, ожидаем результат 1, C=0, O=0
t13:            inc c
                ldi a, 255
                ldi b, 1
                add a, b            ; Готовим C=1
                ldi a, 5
                ldi b, 3
                sbb a, b            ; 5-3-1 = 1
                jnc t13o
                st c, d             ; "Y" = ложный перенос после sbb 5-3-1
t13o:           inc c
                jno t14
                st c, d             ; "Z" = ложное переполнение после sbb 5-3-1

; Случай 14: 16-битная цепочка 0x0100 - 0x0001 = 0x00FF: sub даёт перенос, sbb обязан его учесть
t14:            ldi a, 7            ; Шаг "+7": перепрыгиваем счётчиком проб коды между "Z" и "a"
                add c, a
                mov a, 0
                ldi b, 1
                sub a, b            ; Младший байт: 0-1 = 255, перенос наружу
                ldi a, 1
                ldi b, 0
                sbb a, b            ; Старший байт: 1-0-C = 0, переноса наружу нет
                jz t14o             ; Проба Z обязана пройти до "inc c", который законно
                                    ;   перезаписывает Z
                st c, d             ; "a" = старший байт 0x0100-0x0001 не ноль, цепочка сломана
t14o:           inc c
                jnc tchk
                st c, d             ; "b" = перенос из старшего байта 0x0100-0x0001

; Проверка счётчика: после 28 проб счётчик должен быть ровно на букве "b"
tchk:           mov a, c
                ldi b, 0x62         ; Код буквы "b"
                xor a, b
                jz tdot
                ldi c, 0x23         ; "#" = поток управления пошёл не по плану, часть проб не
                                    ;   выполнилась
                st c, d
tdot:           ldi c, 0x2E         ; Маркер конца "."
                st c, d
                hlt
