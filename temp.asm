; Вот все четыре варианта в синтаксисе v2. Везде сравниваем знаковые a и b через sub a, b; в P-машине считаем, что опкоды jo/jno просто переименованы в jp/jnp — «переход по истинному знаку», новых инструкций нет.

; Пример 1: ошибка при выходе из диапазона, иначе развилка по знаку

; Машина с O (как сейчас):

  sub a, b            ; a - b
  jo error            ; истинный результат вне -128..+127
  js in_neg           ; переполнения нет - S честен
in_pos:               ; в диапазоне, результат >= 0
  ...
in_neg:               ; в диапазоне, результат < 0
  ...
error:
  ...

; Машина с P:

  sub a, b            ; a - b
  jp true_neg         ; истинный знак - минус
  js error            ; P=0, а байт минусовый: S≠P - переполнение
in_pos:               ; в диапазоне, результат >= 0
  ...
true_neg:
  jns error           ; P=1, а байт плюсовый: S≠P - переполнение
in_neg:               ; в диапазоне, результат < 0
  ...
error:
  ...

; Счёт: O-машина — 2 условных перехода, причём ошибка ловится первой же инструкцией. P-машина — 3 условных перехода, проверка ошибки размазана по обеим веткам. Здесь выигрывает O: вопрос «случилась ли беда?» совпадает с хранимым битом.

; Пример 2: только истинный знак, диапазон не волнует

; Машина с O (как сейчас):

  sub a, b            ; a - b
  jo flipped          ; переполнение - S инвертирован
  js true_neg         ; переполнения нет - S честен
  jmp true_pos
flipped:
  jns true_neg        ; байт плюсовый при O=1 - истинный знак минус
true_pos:             ; истинно a >= b
  ...
true_neg:             ; истинно a < b
  ...

; Машина с P:

  sub a, b            ; a - b
  jp true_neg         ; истинный знак - минус
true_pos:             ; истинно a >= b
  ...
true_neg:             ; истинно a < b
  ...

; Счёт: O-машина — 4 инструкции перехода (8 байт), на любом пути исполняются 2–3. P-машина — один переход, 2 байта. Здесь вопрос совпадает с хранимым битом P, и выигрыш кратный.

Итог

Симметрия из нашего разговора видна прямо в байтах: каждая машина делает «свой» вопрос одноходовым, а «чужой» — деревом переходов. Разница между машинами — в цене чужого вопроса: O-машина на чужом вопросе теряет 3 инструкции и вынуждена дублировать переходы в обеих ветках (это тот самый паттерн, который в живом коде подменяют голым js — со всеми его латентными оговорками), P-машина на чужом вопросе теряет одну инструкцию. Ну а дальше частотный аргумент: код вида «пример 2» — это каждое знаковое сравнение в программе, код вида «пример 1» — редкая защитная проверка.
